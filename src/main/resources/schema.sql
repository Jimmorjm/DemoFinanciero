CREATE TABLE CLIENTES (
    ID_CLIENTE INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE_COMPLETO VARCHAR(255),
    DIRECCION VARCHAR(255),
    NUMERO_CLIENTE VARCHAR(255),
    FECHA_CREACION TIMESTAMP,
    FECHA_ACTUALIZACION TIMESTAMP
);


CREATE TABLE CUENTA (
    ID_CUENTA INT AUTO_INCREMENT PRIMARY KEY,
    NUMERO_CUENTA VARCHAR(50),
    ID_CLIENTE INT,
    SALDO DECIMAL(19, 2),
    ESTATUS_CUENTA VARCHAR(255),

    CONSTRAINT FK_CUENTA_CLIENTE
        FOREIGN KEY (ID_CLIENTE)
        REFERENCES CLIENTES (ID_CLIENTE)
);

CREATE TABLE OPERACION (
    ID_OPERACION INT AUTO_INCREMENT PRIMARY KEY,
    FOLIO_OPERACION VARCHAR(100),
    ID_CUENTA INT,
    MONTO DECIMAL(19, 2),
    FECHA_OPERACION TIMESTAMP,
    ESTATUS_OPERACION VARCHAR(255),
    TIPO_OPERACION VARCHAR(255),

    CONSTRAINT FK_OPERACION_CUENTA
        FOREIGN KEY (ID_CUENTA)
        REFERENCES CUENTA (ID_CUENTA)
);

CREATE TABLE EVENTOS (
    ID_EVENTO INT AUTO_INCREMENT PRIMARY KEY,
    ID_OPERACION INT,
    FECHA_EVENTO TIMESTAMP,
    MSG_OPERACION VARCHAR(255),
    SALDO_INICIAL DECIMAL(19, 2),
    SALDO_FINAL DECIMAL(19, 2),
    STATUS_EVENTO VARCHAR(255),
    CONSTRAINT FK_EVENTOS_OPERACION
        FOREIGN KEY (ID_OPERACION)
        REFERENCES OPERACION (ID_OPERACION)
);